def sentiment_label(score: float) -> str:
    if score >= 45:
        return "強力利多"
    if score >= 15:
        return "偏多"
    if score <= -45:
        return "強力利空"
    if score <= -15:
        return "偏空"
    return "中性"


def sentiment_key(score: float) -> str:
    if score >= 15:
        return "bull"
    if score <= -15:
        return "bear"
    return "flat"


def sanity_check() -> None:
    """詞庫不該自我矛盾，也不該和公司名撞在一起。"""
    overlap = set(BULLISH) & set(BEARISH)
    assert not overlap, f"利多利空詞重疊：{overlap}"
    for term, weight in list(BULLISH.items()) + list(BEARISH.items()):
        assert 0 < weight <= 5, f"{term} 權重超出範圍：{weight}"
        assert len(term) >= 2, f"{term} 太短，容易誤判"

    # 反轉詞與推測詞也一律兩字以上：單字的「不」「未」「無」會在
    # 「不動產」「未來」「無塵室」裡誤中，把後面的詞極性整個翻掉。
    for term in NEGATORS:
        assert len(term) >= 2, f"反轉詞 {term} 是單字，會誤中其他詞"
    for term in INTENSIFIERS:
        assert len(term) >= 1, term

    # 詞彙不可以是公司名稱的一部分，否則每則提到該公司的新聞都會被加分。
    from stocks import ALL_TARGETS  # noqa: PLC0415

    names = set()
    for s in ALL_TARGETS:
        names.add(s["name"])
        names.add(s["full_name"])
        names.update(s["aliases"])
    for term in list(BULLISH) + list(BEARISH) + NEGATORS:
        clashes = [n for n in names if term in n]
        assert not clashes, f"詞彙「{term}」出現在公司名 {clashes} 之中"

    ids = [c["id"] for c in CATEGORIES]
    assert len(ids) == len(set(ids)), "分類 id 重複"


