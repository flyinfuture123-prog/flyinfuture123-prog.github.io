def build(now: datetime) -> list:
    out = []
    for title, summary, outlet, tier, hours_ago in RAW:
        published = now - timedelta(hours=hours_ago)
        out.append({
            "title": title,
            "summary": summary,
            "outlet": outlet,
            "outlet_tier": tier,
            "url": "https://example.invalid/fixture",
            "published": published.isoformat(),
            "published_ts": published.timestamp(),
            "source_id": "fixture",
            "tickers": [],
        })
    return out


def main() -> int:
    dest = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "fixtures", "news_sample.json")
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    data = build(datetime.now(TPE))
    with open(dest, "w", encoding="utf-8") as fh:
        json.dump(data, fh, ensure_ascii=False, indent=1)
    print(f"寫入 {dest}（{len(data)} 則）")
    return 0


